// ============================================================================
// Analog Rytm MKII lessons
// Paged UI: every lesson first selects the track (tap a pad / [FX]) and the
// PARAMETER page, then turns the encoder the screen shows for that parameter.
// Encoder letters (A-H) follow params.ts.
// ============================================================================

import type { Lesson, LessonStep, SynthConcept } from '@/types';

type StepIn = Omit<LessonStep, 'concept' | 'principle' | 'explanation' | 'manualReference'> & {
  concept: SynthConcept; principle: string; explanation: string; manualReference: string;
};
const s = (x: StepIn): LessonStep => x;

const TRACK_IDX: Record<string, number> = { BD: 0, SD: 1, RS: 2, CP: 3, BT: 4, LT: 5, MT: 6, HT: 7, CH: 8, OH: 9, CY: 10, CB: 11, FX: 12 };
const PAGE_IDX: Record<string, number> = { TRIG: 0, SRC: 1, SMPL: 2, FLTR: 3, AMP: 4, LFO: 5, TEMPO: 6 };

const track = (name: keyof typeof TRACK_IDX, principle: string, explanation: string): LessonStep => s({
  control: 'track', targetValue: TRACK_IDX[name],
  instruction: name === 'FX' ? 'Press [FX] to select the FX track (the master effects)' : `Tap the ${name} pad - it plays and becomes the active track`,
  concept: 'signal-routing', principle, explanation,
  manualReference: name === 'FX' ? 'p.36 – Editing the FX' : 'p.34 – Editing a sound',
});

const page = (name: keyof typeof PAGE_IDX, label: string, principle: string, explanation: string, concept: SynthConcept = 'signal-routing'): LessonStep => s({
  control: 'page', targetValue: PAGE_IDX[name],
  instruction: `Press the [${name}] PARAMETER key - the screen shows the ${label} page`,
  concept, principle, explanation,
  manualReference: name === 'TEMPO' ? 'p.37 – TEMPO menu' : 'p.34 – PARAMETER pages',
});

const play: LessonStep = s({
  control: 'play', targetValue: true,
  instruction: 'Press [PLAY] (or the Space bar) to start the sequencer',
  concept: 'sequencer-pattern',
  principle: 'A step sequencer is a clock plus a memory: on every tick it reads the next step and fires whatever trigs are stored there.',
  explanation: 'Leave it running - every change you make is heard on the next pass of the 16 steps.',
  manualReference: 'p.37 – The sequencer',
});

const experiment = (instruction: string, principle: string, explanation: string, concept: SynthConcept, manualReference: string): LessonStep =>
  s({ instruction, principle, explanation, concept, manualReference });

